export function validateQuestionDefinitions(bank = questions) {
  const errors = [];
  const ids = new Set();
  for (const [key, question] of Object.entries(bank)) {
    if (!question.id || key !== question.id || ids.has(question.id)) errors.push(`รหัสคำถามซ้ำหรือไม่ตรงกัน: ${key}`);
    ids.add(question.id);
    const options = question.options || [];
    const optionIds = options.map(item => item.id);
    if (!['single', 'multiple'].includes(question.type) || !question.prompt?.trim() || !Number.isInteger(question.version)) errors.push(`นิยามคำถามไม่ครบ: ${key}`);
    if (options.length < 2 || new Set(optionIds).size !== optionIds.length || options.some(item => !item.id || !item.text?.trim() || !item.retryFeedback?.trim() || !item.explanation?.trim())) errors.push(`ตัวเลือกไม่ครบหรือซ้ำ: ${key}`);
    const correct = question.correctOptionIds || [];
    if (!correct.length || new Set(correct).size !== correct.length || correct.some(id => !optionIds.includes(id)) || (question.type === 'single' && correct.length !== 1)) errors.push(`เฉลยไม่ถูกต้อง: ${key}`);
  }
  return errors;
}
